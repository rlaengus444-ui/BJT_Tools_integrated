"""Snapshot BJT assets and record dynamic imports without touching production."""
from __future__ import annotations
import ast
import base64
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import shutil
import sys
import struct
import warnings
import zipfile
import zlib

HERE = Path(__file__).resolve().parent
SOURCE = Path(os.environ.get('BJT_SOURCE_DIR', str(HERE.parent))).expanduser().resolve()
STAGE = HERE / 'app-source'
STAGE.mkdir(exist_ok=True)

# Only product documents join the embedded runtime; QA reports stay with the build.
PRODUCT_DOCUMENTS = {'사용_안내.txt', 'CHITU_THIRD_PARTY_NOTICES.md'}
for path in SOURCE.iterdir():
    if path.is_file() and (path.suffix.lower() in ('.py', '.pyw', '.json') or
                           path.name in PRODUCT_DOCUMENTS):
        shutil.copy2(path, STAGE / path.name)
for name in ('sources', 'manuals', 'chitu_overlap'):
    shutil.copytree(SOURCE / name, STAGE / name, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns('__pycache__', '*.pyc', '*.nbi', '*.nbc'))
# Development-only, opt-in frozen verification. These fixtures create files in
# a fresh temporary folder; they never load the original desktop applications.
validation = STAGE / 'frozen_validation'
validation.mkdir(exist_ok=True)
helpers = {'slice_fixtures.py': HERE.parent / 'integration/slices/regression_suite.py',
           'bjt_fixtures.py': HERE.parent / 'integration/bjt/pipeline_fixtures.py',
           'thermal_fixtures.py': HERE.parent / 'integration/thermal/thermal_parity.py'}
for name, source in helpers.items():
    bundled_helper = HERE / 'helpers' / name
    if bundled_helper.is_file():
        source = bundled_helper
    shutil.copy2(source, validation / name)
for source in (SOURCE / 'tests').glob('test_*.py'):
    shutil.copy2(source, validation / source.name)
# Inputs are generated by this normal Python test driver, never by the EXE.
# Product operations only read archives; some endpoint policies deny .zip writes.
zip_inputs = validation / 'zip_inputs'
images = zip_inputs / 'images'
images.mkdir(parents=True, exist_ok=True)
def fixture_png(value):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', 10, 9, 8, 0, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress((b'\0' + bytes([value]) * 10) * 9)) + chunk(b'IEND', b''))
for index, value in enumerate((0, 40, 80)):
    (images / f'{index}.png').write_bytes(fixture_png(value))
for name in ('layers', 'different', 'corrupt', 'duplicate'):
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', UserWarning)
        with zipfile.ZipFile(zip_inputs / (name + '.zip'), 'w', compression=zipfile.ZIP_DEFLATED) as archive:
            for index, value in enumerate((0, 40, 80)):
                content = fixture_png(value + 1 if name == 'different' and index == 1 else value)
                if name == 'corrupt' and index == 1:
                    content = b'\x89PNG\r\n\x1a\ntruncated'
                archive.writestr(f'nested/{index}.png', content)
            if name == 'duplicate':
                archive.writestr('nested/0.png', fixture_png(0))
licenses = STAGE / 'licenses'
inventory = []
# Include the interpreter license as well as installed distribution licenses.
python_license = next((Path(sys.prefix) / name for name in ('LICENSE_PYTHON.txt', 'LICENSE.txt')
                       if (Path(sys.prefix) / name).is_file()), None)
if python_license is None:
    raise RuntimeError('CPython license missing: expected LICENSE_PYTHON.txt or LICENSE.txt in sys.prefix')
python_license_target = licenses / 'Python' / python_license.name
python_license_target.parent.mkdir(parents=True, exist_ok=True)
shutil.copy2(python_license, python_license_target)
inventory.append({'distribution': 'CPython', 'version': sys.version.split()[0],
                  'role': 'Python runtime',
                  'license_files': [str(python_license_target.relative_to(STAGE))]})
runtime_distributions = ('numpy', 'scipy', 'Pillow', 'scikit-image', 'trimesh', 'shapely', 'numba', 'llvmlite',
    'rtree', 'opencv-python', 'tkinterdnd2', 'vtk', 'matplotlib', 'tifffile', 'pypng', 'imagecodecs',
    'networkx', 'ImageIO', 'lazy-loader', 'packaging', 'contourpy', 'cycler', 'fonttools', 'kiwisolver',
    'pyparsing', 'python-dateutil', 'six', 'PyInstaller', 'manifold3d', 'python-fcl', 'plotly', 'narwhals')
for name in runtime_distributions:
    distribution = importlib.metadata.distribution(name)
    entries = []
    for item in distribution.files or ():
        if (not str(item).startswith('..') and
            (item.name.lower().startswith(('license', 'copying', 'notice')) or
             any(part.lower() == 'licenses' for part in item.parts))):
            source = Path(distribution.locate_file(item))
            if source.is_file():
                target = licenses / name / Path(str(item))
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, target)
                entries.append(str(target.relative_to(STAGE)))
    if name == 'pypng' and not entries:
        # This wheel advertises LICENCE in METADATA but omits that file; the
        # complete original MIT notice is embedded in png.py's leading header.
        source = Path(distribution.locate_file('png.py'))
        target = licenses / name / 'LICENCE-from-png-header.txt'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source.read_text(encoding='utf-8').split('\"\"\"', 1)[0], encoding='utf-8')
        entries.append(str(target.relative_to(STAGE)))
    inventory.append({'distribution': name, 'version': distribution.version,
                      'role': 'build tool/bootloader' if name == 'PyInstaller' else 'bundled library',
                      'license_files': entries})
for name in ('tcl8.6', 'tk8.6'):
    source = Path(sys.prefix) / 'Library/lib' / name / 'license.terms'
    if source.is_file():
        target = licenses / name / 'license.terms'
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
licenses.mkdir(exist_ok=True)
(licenses / 'inventory.json').write_text(json.dumps(inventory, ensure_ascii=False, indent=2), encoding='utf-8')
manifest = json.loads((STAGE / 'source_manifest.json').read_text(encoding='utf-8'))
checks = []
for item in manifest['tools']:
    path = STAGE / item['source']
    checks.append({'path': item['source'], 'valid': hashlib.sha256(path.read_bytes()).hexdigest() == item['sha256']})
for item in manifest.get('dependencies', []):
    path = STAGE / item['path']
    checks.append({'path': item['path'], 'valid': hashlib.sha256(path.read_bytes()).hexdigest() == item['sha256']})
upstream_mismatches = [item['path'] for item in checks if not item['valid']]
if upstream_mismatches:
    tool_paths = {item['source'] for item in manifest['tools']}
    if '--allow-staging-dependency-refresh' not in sys.argv or tool_paths.intersection(upstream_mismatches):
        raise SystemExit('Snapshot integrity failed: ' + repr(checks))
    # Prototype-only escape hatch: never edit production's manifest and never
    # re-sign original tool source. Final release preparation uses strict mode.
    for dependency in manifest.get('dependencies', []):
        dependency['sha256'] = hashlib.sha256((STAGE / dependency['path']).read_bytes()).hexdigest()
    (STAGE / 'source_manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
    for item in checks:
        item['valid'] = True

local = {p.stem for p in STAGE.glob('*.py')}
imports = set()
def inspect(tree):
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imports.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
            imports.add(node.module)
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in ('_ensure_import', 'ensure_package'):
            if node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                imports.add(node.args[0].value)

for path in list(STAGE.glob('*.py')) + list((STAGE / 'sources').glob('*.py')) + list((STAGE / 'chitu_overlap').rglob('*.py')):
    tree = ast.parse(path.read_text(encoding='utf-8-sig'))
    inspect(tree)
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id in ('_LATTICE_CORE_B64', '_RECON_CORE_B64'):
            inspect(ast.parse(zlib.decompress(base64.b64decode(ast.literal_eval(node.value))).decode('utf-8')))
# Tool sources are executed as data, so their standard-library imports are also
# hidden from PyInstaller's normal module graph (e.g. M1's decimal support).
imports = sorted(name for name in imports if name != '__future__')
record = {'tool_count': len(manifest['tools']), 'source_checks': checks, 'hiddenimports': imports,
          'prototype_upstream_mismatches': upstream_mismatches}
(HERE / 'build_inputs.json').write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps({'tools': record['tool_count'], 'assets_valid': len(checks), 'hiddenimports': imports}, ensure_ascii=True))
